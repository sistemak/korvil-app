// ================= ANCHOR LOGIC =================

export function ensureSameQuantity(jsonContacts, jsContacts) {
  const jLen = jsonContacts?.length ?? 0;
  const jsLen = jsContacts?.length ?? 0;
  if (jLen !== jsLen) {
    console.warn(`[ANCHOR] Divergência quantidade: JSON=${jLen} JS=${jsLen}`);
    return false;
  }
  if (jLen !== ANCHOR_CONFIG.totalEsperado) {
    console.warn(`[ANCHOR] Total inesperado: ${jLen} esperado ${ANCHOR_CONFIG.totalEsperado}`);
  }
  return true;
}

export function syncFromJsonToJs(jsonData) {
  const jsonContacts = jsonData.contacts || jsonData;
  if (!ensureSameQuantity(jsonContacts, contacts)) {
    // força sync para maior array
    const merged = jsonContacts.length >= contacts.length ? jsonContacts : contacts;
    if (typeof localStorage !== 'undefined') {
      localStorage.setItem('ktp_contacts_anchor', JSON.stringify({ lastSync: new Date().toISOString(), total: merged.length, source: 'json->js' }));
    }
    try {
      const ch = new BroadcastChannel('ktp-anchor-sync');
      ch.postMessage({ type: 'SYNC_JSON_TO_JS', total: merged.length, timestamp: Date.now() });
      ch.close();
    } catch {}
    return merged;
  }
  return jsonContacts;
}

export function syncToJsonFromJs(jsContacts) {
  if (!ensureSameQuantity(jsContacts, contacts)) {
    const merged = jsContacts;
    if (typeof localStorage !== 'undefined') {
      localStorage.setItem('ktp_contacts_anchor', JSON.stringify({ lastSync: new Date().toISOString(), total: merged.length, source: 'js->json' }));
    }
    try {
      const ch = new BroadcastChannel('ktp-anchor-sync');
      ch.postMessage({ type: 'SYNC_JS_TO_JSON', total: merged.length, timestamp: Date.now() });
      ch.close();
    } catch {}
    return { contacts: merged, meta: { total: merged.length, lastSync: new Date().toISOString() } };
  }
  return { contacts: jsContacts, meta: { total: jsContacts.length, lastSync: new Date().toISOString() } };
}

export function watchChanges(callback) {
  let bc;
  try {
    bc = new BroadcastChannel('ktp-anchor-sync');
    bc.onmessage = (ev) => {
      console.log('[ANCHOR] Broadcast recebido:', ev.data);
      if (callback) callback(ev.data);
    };
  } catch {}

  const onStorage = (e) => {
    if (e.key === 'ktp_contacts_anchor') {
      console.log('[ANCHOR] localStorage anchor mudou:', e.newValue);
      if (callback) {
        try { callback(JSON.parse(e.newValue || '{}')); } catch {}
      }
    }
  };

  const onOnline = () => {
    console.log('[ANCHOR] Voltou online - verificando sync');
    if (callback) callback({ type: 'ONLINE_SYNC_CHECK' });
  };

  if (typeof window !== 'undefined') {
    window.addEventListener('storage', onStorage);
    window.addEventListener('online', onOnline);
  }

  // sync offline/online: persiste anchor
  if (typeof localStorage !== 'undefined') {
    const current = {
      jsonPath: ANCHOR_CONFIG.jsonPath,
      jsPath: ANCHOR_CONFIG.jsPath,
      lastSync: new Date().toISOString(),
      total: contacts.length,
      anchorId: ANCHOR_CONFIG.anchorId
    };
    localStorage.setItem('ktp_anchor_config', JSON.stringify(current));
  }

  return () => {
    if (bc) bc.close();
    if (typeof window !== 'undefined') {
      window.removeEventListener('storage', onStorage);
      window.removeEventListener('online', onOnline);
    }
  };
}

